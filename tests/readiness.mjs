 const section = name => rows.filter(r => r[0] === name)
 assert.deepEqual(Object.fromEntries(section('readiness').map(r => [r[1],Number(r[3])])),report.readiness)
 assert.deepEqual(section('requirement').map(r => [r[1],r[3]]),report.filtered_requirements.map(r => [r.ref,r.state === 'excluded'?'excluded':r.ready?'ready':'not ready']))
 assert.equal(section('requirement').filter(r => r[3] === 'ready').length,report.filtered_requirements.filter(r => r.state === 'included' && r.ready).length)

import assert from 'node:assert/strict'
// RISK-002: the owner reviews the library, changes a copied scenario, removes a
// suggested link and changes the scoring method without rewriting history.
export async function riskJourney(page, origin, width, capture) {
 const owner = async (path, body) => {
  const r = await page.context().request.post(origin + path, {headers:{origin},data:body})
  assert.equal(r.status(),201, path + ' ' + await r.text()); return r.json()
 }
 const program = await owner('/api/programs', {framework:'iso27001',name:'Northstar ISO 27001 '+width,legal_entity:'Northstar Cloud Inc.',products:['Billing API','Customer portal'],audit_from:'2026-07-01',audit_to:'2027-06-30'})
 assert.ok(program.id)
 const person = await owner('/api/people', {name:'Priya Shah '+width,email:`priya${width}@northstar.test`,kind:'employee'})
 await page.goto(origin + '/app/risks/library')
 const scenario = page.locator('details').filter({has:page.getByText('Account takeover through stolen passwords', {exact:false})}).first()
 await scenario.locator('summary').click()
 await capture(page, `${width}-risk-library`)
 await scenario.getByRole('button',{name:'Add this scenario'}).click()
 await page.waitForURL(/\/app\/risks\/[a-f0-9-]+$/)
 const riskURL = page.url(), riskID = new URL(riskURL).pathname.split('/').at(-1)
 const facts = page.locator('section[aria-labelledby="risk-facts"]')
 await facts.getByLabel('Title',{exact:true}).fill('Workforce account takeover '+width)
 await facts.getByLabel('Scenario',{exact:true}).fill('Phishing against workforce accounts without enforced MFA')
 await facts.getByLabel('Treatment',{exact:true}).selectOption('mitigate')
 await facts.getByLabel('Owner',{exact:true}).selectOption(person.id)
 await facts.getByLabel('Review due',{exact:true}).fill('2027-01-31')
 await facts.getByRole('button',{name:'Save risk',exact:true}).click()
 await page.waitForURL(riskURL)
 assert.equal(await page.getByRole('heading',{name:'Workforce account takeover '+width,exact:true}).count(),1)
 const links = page.locator('section[aria-labelledby="links-title"]')
 const before = await links.getByRole('button',{name:'Unlink',exact:true}).count()
 await links.getByRole('button',{name:'Unlink',exact:true}).first().click()
 await page.waitForURL(riskURL)
 assert.equal(await links.getByRole('button',{name:'Unlink',exact:true}).count(),before-1)
 await capture(page,`${width}-risk-edited`)
 const initial = await (await page.context().request.get(origin+'/api/risks/'+riskID)).json()
 await page.goto(origin+'/app/risks')
 const method = page.locator('section[aria-labelledby="method-title"]')
 await method.getByLabel('Scale',{exact:true}).selectOption('4')
 await method.getByLabel('Likelihood labels',{exact:false}).fill('Unusual, Occasional, Frequent, Imminent')
 await method.getByLabel('Impact labels',{exact:true}).fill('Minor, Material, Major, Severe')
 await method.getByLabel('Likelihood definitions',{exact:false}).fill('Exceptional event\nPossible event\nRecurring event\nExpected soon')
 await method.getByLabel('Impact definitions',{exact:false}).fill('Local disruption\nTeam disruption\nService outage\nBusiness interruption')
 await method.getByLabel('Formula',{exact:true}).selectOption('product')
 await method.getByLabel('Thresholds for product',{exact:false}).fill('Low:3, Medium:8, High:16')
 await method.getByRole('button',{name:'Save a new method revision'}).click()
 await page.waitForURL(/\/app\/risks#method-title$/)
 await capture(page,`${width}-risk-method`)
 await page.goto(riskURL)
 const assessment = page.locator('section[aria-labelledby="assess-title"]')
 await assessment.getByLabel('Kind',{exact:true}).selectOption('inherent')
 await assessment.getByLabel('Likelihood',{exact:true}).fill('4')
 await assessment.getByLabel('Impact',{exact:true}).fill('2')
 await assessment.getByLabel('Notes',{exact:true}).fill('Reassessed after workforce scope review')
 await assessment.getByRole('button',{name:'Add assessment'}).click()
 await page.waitForURL(riskURL)
 const after = await (await page.context().request.get(origin+'/api/risks/'+riskID)).json()
 for(const old of initial.assessments) assert.deepEqual(after.assessments.find(a=>a.id===old.id),old)
 assert.equal(after.assessments.length, initial.assessments.length+1)
 const methodDetail = assessment.locator('details').first()
 await methodDetail.locator('summary').click()
 assert.match(await methodDetail.innerText(), /definitions/)
 await capture(page,`${width}-risk-history`)
 console.log(`PASS RISK-002: library, editing, unlinking and historical scoring UI at ${width}`)
}

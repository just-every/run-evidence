import assert from 'node:assert/strict'
import { frameworkFixture,revisedFrameworkFixture,frameworkColumns } from './framework-fixture.mjs'
// Parent browser proof calls this inside its existing signed-in context at 1440/390.
export async function frameworkBrowserJourney(page,origin,width,capture,fixture={}) {
 const control=fixture.control??'',bytes=frameworkFixture(control),file={name:'customer-addendum.xlsx',mimeType:'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',buffer:bytes}
 await page.goto(origin+'/app/frameworks')
 await capture(page,`${width}-framework-list`)
 const form=page.locator('form[action="/app/frameworks/import"]')
 await form.getByLabel('Framework name',{exact:true}).fill(`Customer addendum ${width}`)
 await form.getByLabel('File (CSV or XLSX)',{exact:true}).setInputFiles(file)
 for(const [field,value] of Object.entries(frameworkColumns))await form.locator(`[name="${field}"]`).fill(value)
 await form.getByRole('button',{name:'Review every row',exact:true}).click()
 await page.getByRole('heading',{name:'Dry run: nothing is admitted yet',exact:true}).waitFor()
 assert.match(await page.locator('main').innerText(),/Duplicate requirement ID/);assert.match(await page.locator('main').innerText(),/Unknown control ID/)
 await capture(page,`${width}-framework-import-review`)
 await page.getByLabel('Same file',{exact:true}).setInputFiles(file)
 await page.getByLabel('Admit 78 valid requirements and exclude 2 refused rows',{exact:true}).check()
 await page.getByRole('button',{name:'Confirm this framework revision',exact:true}).click()
 await page.waitForURL(/\/app\/frameworks\/[a-f0-9-]+$/)
 const path=new URL(page.url()).pathname,detail=await(await page.request.get(origin+path.replace('/app/','/api/'))).json()
 assert.equal(detail.totals.requirements,78);assert.equal(detail.totals.unmapped,control?57:58)
 await capture(page,`${width}-framework-readiness`)
 await page.getByRole('link',{name:`${control?57:58} unmapped`,exact:true}).click()
 await page.getByRole('heading',{name:'Requirements and mappings',exact:true}).waitFor()
 await capture(page,`${width}-framework-unmapped`)
 await page.goto(origin+path)
 const revised=revisedFrameworkFixture(control),reimport=page.locator('form[action="/app/frameworks/import"]')
 await reimport.getByLabel('File (CSV or XLSX)',{exact:true}).setInputFiles({...file,buffer:revised})
 for(const [field,value] of Object.entries(frameworkColumns))await reimport.locator(`[name="${field}"]`).fill(value)
 await reimport.getByRole('button',{name:'Review every row',exact:true}).click()
 await page.getByRole('heading',{name:'Dry run: nothing is admitted yet',exact:true}).waitFor()
 const changes=page.getByRole('table').first()
 assert.match(await changes.innerText(),/ADD-001, ADD-002, ADD-003/);assert.match(await changes.innerText(),/ADD-078/)
 await capture(page,`${width}-framework-reimport-review`)
 await page.getByLabel('Same file',{exact:true}).setInputFiles({...file,buffer:revised})
 await page.getByRole('button',{name:'Confirm this framework revision',exact:true}).click()
 await page.waitForURL(origin+path)
 const after=await(await page.request.get(origin+path.replace('/app/','/api/'))).json();assert.equal(after.totals.requirements,77);assert.equal(after.totals.removed,1)
 const removed=after.requirements.find(r=>r.ref==='ADD-078')
 await page.goto(origin+path+'/requirements/'+removed.id)
 await page.getByRole('heading',{name:'Historical definitions',exact:true}).waitFor()
 assert.match(await page.locator('main').innerText(),/history retained/)
 await capture(page,`${width}-framework-removed-history`)
 await page.goto(origin+path+'/revisions/1')
 await page.getByRole('heading',{name:'Recorded revision',exact:true}).waitFor()
 await capture(page,`${width}-framework-original-revision`)
 const original=await page.request.get(origin+path+'/revisions/1/file');assert.equal(original.status(),200);assert.deepEqual(await original.body(),bytes)
 console.log(`PASS CONTROL-001 reviewed framework import, unmapped readiness, revised changes and retained history at ${width}`)
 return path
}

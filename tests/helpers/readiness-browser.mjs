import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import { browserReadinessClient, seedReadiness, assertReadiness, csvRows } from './readiness-fixture.mjs'
const fixtures = new Map()

// Run the two viewports together before other journeys mutate shared controls.
// Seed through the owner APIs, then use the directory, denominator, filters,
// source drill-down and export links exactly as the owner does.
export async function readinessJourney(page, origin, width, capture) {
 const client = browserReadinessClient(page.context().request,origin)
 if (!fixtures.has(origin)) {
  const seeded = await seedReadiness(client,{name:'Northstar SOC 2 Type II readiness'})
  fixtures.set(origin,{program:seeded.program,base:seeded.base})
  await seeded.close()
 }
 const fixture = fixtures.get(origin), base = '/app/programs/'+fixture.program.id
 const current = await client.get(fixture.base+'/board')
 assertReadiness(current,47,94)
 await page.goto(origin+'/app/programs')
 const directory = page.locator('form').filter({has:page.getByLabel('Framework',{exact:true})})
 await directory.getByLabel('Framework',{exact:true}).selectOption('soc2')
 await directory.getByLabel('Product',{exact:true}).fill('Billing API')
 await directory.getByRole('button',{name:'Filter programs',exact:true}).click()
 await page.waitForURL(url=>url.pathname === '/app/programs' && url.searchParams.get('product') === 'Billing API')
 await capture(page,`${width}-readiness-directory`)
 await page.getByRole('link',{name:fixture.program.name,exact:true}).click()
 await page.waitForURL(origin+base)
 const readiness = page.locator('section[aria-labelledby="readiness-title"]')
 assert.match(await readiness.innerText(),/94% ready/)
 assert.match(await readiness.innerText(),/47 of 50 requirements ready/)
 await capture(page,`${width}-readiness-94`)
 await page.locator(`a[href="${base}?show=ready#requirements"]`).first().click()
 await page.waitForURL(url=>url.pathname===base&&url.searchParams.get('show')==='ready')
 await page.locator('#requirements tbody tr').first().waitFor()
 assert.equal(await page.locator('#requirements tbody tr').count(),47,'ready-filter row count reconciles to 47 ready requirements')
 await capture(page,`${width}-readiness-ready-denominator`)
 await page.locator(`a[href="${base}?show=not-ready#requirements"]`).first().click()
 await page.waitForURL(url=>url.pathname===base&&url.searchParams.get('show')==='not-ready')
 await page.locator('#requirements tbody tr').first().waitFor()
 const missing = page.locator('#requirements tbody tr')
 assert.equal(await missing.count(),3)
 assert.match(await missing.allTextContents().then(rows=>rows.join(' ')),/CC1\.2/)
 await page.locator('#requirements').getByRole('link',{name:'GOV-03',exact:true}).first().click()
 await page.waitForURL(/\/app\/controls\/[a-f0-9-]+$/)
 await page.locator('section[aria-labelledby="control-evidence"]').getByRole('link').first().click()
 await page.waitForURL(/\/app\/requirements\/[a-f0-9-]+$/)
 assert.match(await page.locator('main').innerText(),/missing/)
 await capture(page,`${width}-readiness-missing-source`)
 await page.goto(origin+base)
 await page.getByRole('link',{name:'Board and auditor report',exact:true}).click()
 await page.getByRole('heading',{name:'Requirement denominator',exact:true}).waitFor()
 assert.equal(await page.locator('section').filter({has:page.getByRole('heading',{name:'Requirement denominator',exact:true})}).locator('tbody tr').count(),current.requirements.length)
 await page.getByRole('heading',{name:'Checklist',exact:true}).waitFor()
 assert.match(await page.locator('main').innerText(),/Trust center/)
 assert.match(await page.locator('main').innerText(),/unavailable/i)
 await capture(page,`${width}-readiness-board`)
 const filter = page.locator('form').filter({has:page.getByLabel('Severity',{exact:true})})
 await filter.getByLabel('Product',{exact:true}).fill('Billing API')
 await filter.getByLabel('Owner',{exact:true}).selectOption(current.requirements.find(r=>r.ref === 'CC2.3').controls.find(c=>c.library_id === 'GOV-09').owner_person_id)
 await filter.getByRole('button',{name:'Filter',exact:true}).click()
 await page.waitForURL(url=>url.pathname === base+'/board' && url.searchParams.has('owner'))
 assert.match(await page.locator('main').innerText(),/94% ready/)
 assert.equal(await page.locator('#requirements tbody tr').count(),1)
 await filter.getByLabel('Severity',{exact:true}).selectOption('low')
 await filter.getByRole('button',{name:'Filter',exact:true}).click()
 await page.waitForURL(url=>url.pathname === base+'/board' && url.searchParams.get('severity') === 'low')
 const filtered = await client.get(fixture.base+'/board?severity=low')
 assert.deepEqual(filtered.readiness,current.readiness)
 assert.equal(filtered.filtered_requirements.length,0)
 assert.match(await page.locator('main').innerText(),/94% ready/)
 await capture(page,`${width}-readiness-filter-preserves-score`)
 await page.goto(origin+base+'/board')
 const [download] = await Promise.all([page.waitForEvent('download'),page.getByRole('link',{name:'Export CSV',exact:true}).click()])
 const exported = await readFile(await download.path(),'utf8'), rows = csvRows(exported).slice(1)
 assert.equal(rows.filter(r => r[0] === 'requirement' && r[3] === 'ready').length,47,'CSV ready rows reconcile to 47 ready requirements')
 assert.equal(rows.filter(r => r[0] === 'requirement').length,current.requirements.length)
 assert.equal(rows.find(r => r[0] === 'readiness' && r[1] === 'readiness_percent')[3],'94')
 assert.doesNotMatch(exported,/\bcertified\b/i)
 const periods = page.locator('section').filter({has:page.getByRole('heading',{name:'Audit periods',exact:true})})
 const snapshots = periods.locator('a[href*="snapshot="]')
 if (await snapshots.count()) {
  const href = await snapshots.first().getAttribute('href')
  await snapshots.first().click()
  assert.ok(new URL(page.url()).searchParams.has('snapshot'))
  const report = await client.get(fixture.base+'/board?'+new URL(href,origin).searchParams)
  assert.equal(report.snapshot_day,new URL(page.url()).searchParams.get('snapshot'))
  await capture(page,`${width}-readiness-historical`)
 } else {
  assert.match(await periods.innerText(),/No snapshot|not recorded/i)
  await capture(page,`${width}-readiness-unrecorded-history`)
 }
 assert.doesNotMatch(await page.locator('main').innerText(),/\bcertified\b/i)
 console.log(`PASS READINESS-001: 94%, denominator, missing proof, filters and reconciled CSV at ${width}`)
}
